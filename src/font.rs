pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// The 5x7 pattern of `c` as rows of bits (bit 4 is the leftmost column). Unknown characters draw as `?`.
pub fn glyph(c: char) -> [u8; GLYPH_H] {
    let rows = GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .or_else(|| GLYPHS.iter().find(|(g, _)| *g == '?'))
        .map(|(_, r)| r)
        .unwrap_or(&GLYPHS[0].1);
    let mut out = [0u8; GLYPH_H];
    for (y, row) in rows.iter().enumerate() {
        for (x, ch) in row.chars().enumerate() {
            if ch == '#' {
                out[y] |= 1 << (GLYPH_W - 1 - x);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_ascii_character_has_a_distinct_glyph() {
        let mut seen: Vec<([u8; GLYPH_H], char)> = Vec::new();
        for c in (0x20u8..0x7f).map(char::from) {
            assert!(GLYPHS.iter().any(|(g, _)| *g == c), "missing {c:?}");
            let g = glyph(c);
            if c != ' ' {
                assert!(g.iter().any(|r| *r != 0), "{c:?} is blank");
            }
            if let Some((_, other)) = seen.iter().find(|(s, _)| *s == g) {
                panic!("{c:?} and {other:?} look identical");
            }
            seen.push((g, c));
        }
    }

    #[test]
    fn every_row_is_five_columns_and_there_are_seven_rows() {
        for (c, rows) in GLYPHS {
            for r in rows {
                assert_eq!(r.chars().count(), GLYPH_W, "{c:?}: {r}");
                assert!(r.chars().all(|ch| ch == '#' || ch == '.'));
            }
        }
    }

    #[test]
    fn unknown_characters_fall_back_to_a_question_mark() {
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(glyph('A')[0], 0b01110);
    }
}
